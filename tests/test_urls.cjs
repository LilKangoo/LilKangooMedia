const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const path = require('path');
const source = fs.readFileSync(path.join(__dirname,'../01_COPY_TO_PROJECT_ROOT/assets/lkm-v3/phase35-images.js'),'utf8');
const window = { location: {href:'https://lilkangoomedia.com/',origin:'https://lilkangoomedia.com'} };
const context = { window, URL, URLSearchParams };
vm.runInNewContext(source, context);
const opt=window.LKM35Images;
assert(opt);
const local='/assets/images/wedding-6.jpeg';
const supa='https://nvronzbkvwyyllbuidhw.supabase.co/storage/v1/object/public/portfolio/uploads/studio/2026-11/photo.jpg';
const remote='https://otherdomain.com/photo.jpg';
assert(opt.url(local,720).includes('w=720&q=86'));
assert(opt.url(supa,720).includes('nvronzbkvwyyllbuidhw'));
assert(opt.srcset(supa).split(', ').length===6);
assert(!opt.url(remote,480));
assert(!opt.url('/admin.html',480));
assert(!opt.url('/assets/lkm-v3/brand/logo-orange.png',480));
const attrs=opt.htmlAttrs(supa);
assert(attrs.includes('srcset="'));assert(attrs.includes('&amp;w=720'));
const fake={dataset:{lkm35Original:local},removed:[],removeAttribute(x){this.removed.push(x)},src: ''};
assert(opt.recover(fake)===true);
assert(fake.src===local);
assert(fake.removed.join(',')==='srcset,sizes');
assert(opt.recover(fake)===false);
console.log('PASS: allowed Netlify & Supabase URLs, srcset, HTML escaping, original fallback, excluded assets');
